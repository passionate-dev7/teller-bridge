// Runs every suite and mutation check and writes TESTS.md: what was run, what went red when a guard was broken, what went green after.
// Also queries the chipnet txids of the recorded swaps back from Electrum. usage: node scripts/evidence.mjs [desk.sqlite ...]
import { spawnSync } from 'node:child_process';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { decodeTransaction, hexToBin, lockingBytecodeToCashAddress } from '@bitauth/libauth';
import { Network } from 'cashscript';
import { Store } from '../desk/store.js';
import { ElectrumChain } from '../desk/chains.js';

const root = new URL('..', import.meta.url).pathname;
const run = (cmd, args, opts = {}) => spawnSync(cmd, args, { cwd: root, encoding: 'utf8', env: { ...process.env, FOUNDRY_DISABLE_NIGHTLY_WARNING: '1' }, ...opts });
const stamp = new Date().toISOString();
const count = (out, k) => (out.match(new RegExp('^ℹ ' + k + ' (\\d+)', 'm')) ?? [])[1];
const table = (out) => out.split('\n').filter((l) => /^[┌├└│]/.test(l)).join('\n').replace(/[┌┐├┤└┘┬┴┼─│]/g, (c) => (c === '│' ? '|' : '')).replace(/\n\s*\n/g, '\n');

const sections = [];
const node = run('node', ['--test', 'test/*.test.js'], { shell: true });
const files = run('sh', ['-c', 'ls test/*.test.js']).stdout.trim().split('\n');
const perFile = files.map((f) => { const r = run('node', ['--test', f]); return '| ' + f + ' | ' + count(r.stdout, 'tests') + ' | ' + count(r.stdout, 'pass') + ' | ' + count(r.stdout, 'fail') + ' |'; });
const forge = run('forge', ['test'], { cwd: root + 'contracts/evm' });
const forgeLine = (forge.stdout.match(/(\d+) tests passed, (\d+) failed/) ?? []).slice(1);
const mb = run('node', ['scripts/mutate-bch.mjs']);
const me = run('node', ['scripts/mutate-evm.mjs']);
const md = run('node', ['scripts/mutate-desk.mjs'], { maxBuffer: 1 << 26 });

// the recorded swaps, read back from the chain
const dbs = process.argv.slice(2);
const chain = new ElectrumChain(Network.CHIPNET);
/** a public Electrum server drops connections now and then: try a few times before saying a lookup failed */
const retry = async (fn, n = 5) => { for (let i = 0; ; i++) { try { return await fn(); } catch (e) { if (i >= n - 1) throw e; await new Promise((r) => setTimeout(r, 3000)); } } };
const swaps = dbs.flatMap((db) => new Store(db).recent(['done'], 50));
const legs = [];
for (const s of swaps) for (const [k, txid] of Object.entries(s.txs)) {
  if (!/^[0-9a-f]{64}$/.test(txid)) continue;
  let confs = 'n/a';
  try { const t = await retry(() => chain.performRequest('blockchain.transaction.get', txid, true)); confs = String(t.confirmations ?? 0); } catch (e) { confs = 'lookup failed'; }
  legs.push('| ' + s.dir + ' | ' + k + ' | `' + txid + '` | ' + confs + ' |');
}

// extra legs worth reading back in full (refund paths): outputs decoded from the raw transaction
const extraFile = root + 'docs/evidence/live-legs.json';
const extra = [];
if (existsSync(extraFile)) for (const { label, txid } of JSON.parse(readFileSync(extraFile, 'utf8'))) {
  const raw = await retry(() => chain.getRawTransaction(txid));
  const info = await retry(() => chain.performRequest('blockchain.transaction.get', txid, true));
  const tx = decodeTransaction(hexToBin(raw));
  const outs = tx.outputs.map((o) => lockingBytecodeToCashAddress({ bytecode: o.lockingBytecode, prefix: 'bchtest', tokenSupport: true }).address + ' ' + (o.token ? o.token.amount + ' units' : 'no tokens')).join('; ');
  extra.push('- ' + label + '. `' + txid + '`, locktime ' + tx.locktime + ', ' + (info.confirmations ?? 0) + ' confirmations, pays ' + outs + '.');
}

writeFileSync(root + 'TESTS.md', [
  '# Test evidence',
  '',
  'Generated by `node scripts/evidence.mjs` at ' + stamp + '. Every check below can fail: each rule has a mutant that deletes it, and the suite must turn red.',
  '',
  '## Suites',
  '',
  '| File | tests | pass | fail |',
  '|---|---|---|---|',
  ...perFile,
  '| contracts/evm/test/DeskLock.t.sol (forge) | ' + (Number(forgeLine[0]) + Number(forgeLine[1])) + ' | ' + forgeLine[0] + ' | ' + forgeLine[1] + ' |',
  '',
  'All node suites in one run: ' + count(node.stdout, 'tests') + ' tests, ' + count(node.stdout, 'pass') + ' pass, ' + count(node.stdout, 'fail') + ' fail.',
  '',
  '## Break the guard, see red, restore, see green',
  '',
  '### BCH covenant, contracts/bch/SwapLock.cash (each require replaced by require(true), tests in test/bch-contract.test.js)',
  '',
  '```',
  table(mb.stdout),
  '```',
  '',
  '### Base contract, contracts/evm/src/DeskLock.sol (guards deleted, boundaries flipped, payees swapped, forge test)',
  '',
  '```',
  table(me.stdout),
  '```',
  '',
  '### Desk engine and client quote checks (desk/engine.js, lib/client.js; tests in test/desk.test.js and test/client.test.js)',
  '',
  '```',
  table(md.stdout),
  '```',
  '',
  'ORIGINAL is the unmodified code (green). Each other row is the same suite run against a copy with one rule broken: killed means the suite went red.',
  '',
  '## Recorded swaps read back from chipnet',
  '',
  'Block confirmations queried from the Electrum server at generation time.',
  '',
  '| direction | leg | txid | confirmations |',
  '|---|---|---|---|',
  ...legs,
  '',
  '## Refund paths read back from chipnet',
  '',
  'The user locks and then does nothing, with short windows (scripts/e2e-refund.mjs). The BCH leg runs on real chipnet; the BCH refund opens only once the chain median time past reaches the refund time, about an hour behind the wall clock.',
  '',
  ...extra,
  '',
].join('\n'));
console.log('wrote TESTS.md', { exitCodes: { node: node.status, forge: forge.status, bch: mb.status, evm: me.status, desk: md.status }, legs: legs.length });
